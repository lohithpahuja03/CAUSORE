"""
CAUSORE RCA Investigation Report Generator & Exporter
Adhering to BRAIN.md Principle 3 (Fact vs Inference Separation) & Section 18.
Exports Markdown, JSON, and Print-Ready HTML.
"""

import json
from typing import Dict, Any, List, Optional
from datetime import datetime, timezone


class ReportGenerator:
    """Generates standardized, evidence-backed RCA documents across multiple formats."""

    def compile_report(
        self,
        investigation_id: str,
        title: str,
        severity: str,
        environment: str,
        duration_minutes: int,
        executive_summary: str,
        hypotheses: List[Dict[str, Any]],
        anomalies: List[Dict[str, Any]],
        critical_events: List[Dict[str, Any]],
        missing_evidence: List[str],
        action_items: List[str]
    ) -> Dict[str, Any]:
        return {
            "investigation_id": investigation_id,
            "title": title,
            "severity": severity,
            "environment": environment,
            "duration_minutes": duration_minutes,
            "executive_summary": executive_summary,
            "top_hypotheses": hypotheses,
            "anomalies_detected": anomalies,
            "critical_timeline_events": critical_events,
            "missing_evidence_summary": missing_evidence,
            "action_items": action_items,
            "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        }

    def export_markdown(self, data: Dict[str, Any]) -> str:
        """Render high-density GitHub-flavored Markdown RCA artifact."""
        hypo_md = []
        for idx, h in enumerate(data.get("top_hypotheses", []), 1):
            supporting = "\n".join(f"  - {e}" for e in h.get("supporting_evidence", []))
            contradicting = "\n".join(f"  - {e}" for e in h.get("contradicting_evidence", [])) or "  - None observed in supplied telemetry"
            missing = "\n".join(f"  - {m}" for m in h.get("missing_evidence", [])) or "  - None identified"
            verification = "\n".join(f"  {i+1}. `{v}`" for i, v in enumerate(h.get("recommended_verification", [])))

            hypo_md.append(f"""### Candidate #{idx}: {h.get('candidate')}
- **Confidence:** {int(h.get('confidence', 0)*100)}%
- **Status:** `{h.get('status', 'INFERRED')}`
- **Affected Services:** {', '.join(h.get('affected_services', []))}

**Supporting Evidence:**
{supporting}

**Contradicting Evidence:**
{contradicting}

**Telemetry Gaps & Missing Evidence:**
{missing}

**Recommended Verification Actions:**
{verification}
""")

        anom_md = "\n".join(
            f"- **[{a.get('type', a.get('anomaly_type', 'ANOMALY')).upper()}]** `{a.get('service')}` (Score: {int(a.get('score', 0)*100)}%): {a.get('description')}"
            for a in data.get("anomalies_detected", [])
        ) or "- None isolated"

        actions_md = "\n".join(f"{i+1}. {item}" for i, item in enumerate(data.get("action_items", [])))

        return f"""# CAUSORE INVESTIGATION REPORT
## {data.get('title')}

| Incident ID | Severity | Environment | Duration | Generated At |
| :--- | :--- | :--- | :--- | :--- |
| `{data.get('investigation_id')}` | **{data.get('severity')}** | `{data.get('environment')}` | {data.get('duration_minutes')} mins | {data.get('generated_at')} |

---

## 1. Executive Summary
{data.get('executive_summary')}

---

## 2. Root-Cause Candidate Hypotheses
{chr(10).join(hypo_md)}

---

## 3. Detected Statistical Anomalies
{anom_md}

---

## 4. Telemetry Gaps & Unmonitored Blindspots
{chr(10).join(f"- {gap}" for gap in data.get('missing_evidence_summary', []))}

---

## 5. Preventative Action Items & Runbooks
{actions_md}

---
*Generated by CAUSORE — Evidence first. Investigation second. Explanation third.*
"""

    def export_json(self, data: Dict[str, Any]) -> str:
        """Render machine-readable JSON artifact."""
        return json.dumps(data, indent=2)

    def export_html(self, data: Dict[str, Any]) -> str:
        """Render clean, print-ready HTML template."""
        return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>CAUSORE RCA: {data.get('title')}</title>
  <style>
    body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; background: #0a0e17; color: #f8fafc; padding: 2rem; line-height: 1.6; max-width: 900px; margin: 0 auto; }}
    h1, h2, h3 {{ color: #ffffff; border-bottom: 1px solid rgba(255,255,255,0.1); padding-bottom: 0.5rem; }}
    .badge {{ padding: 0.2rem 0.5rem; border-radius: 4px; font-size: 0.8rem; font-weight: bold; background: #ef4444; color: white; display: inline-block; }}
    .card {{ background: #131924; border: 1px solid rgba(255,255,255,0.08); border-radius: 8px; padding: 1.25rem; margin-bottom: 1rem; }}
    code {{ font-family: monospace; color: #38bdf8; background: #090d14; padding: 0.15rem 0.35rem; border-radius: 3px; }}
    ul {{ padding-left: 1.25rem; }}
    @media print {{ body {{ background: #fff; color: #000; }} .card {{ border: 1px solid #ccc; background: #f9f9f9; }} }}
  </style>
</head>
<body>
  <h1>CAUSORE Incident Investigation Report</h1>
  <p><span class="badge">{data.get('severity')}</span> <strong>{data.get('title')}</strong></p>
  <p>Investigation ID: <code>{data.get('investigation_id')}</code> | Duration: {data.get('duration_minutes')} mins | Generated: {data.get('generated_at')}</p>
  
  <h2>Executive Summary</h2>
  <div class="card">{data.get('executive_summary')}</div>
  
  <h2>Evaluated Root Causes</h2>
  {"".join(f'<div class="card"><h3>{h.get("candidate")} (Confidence: {int(h.get("confidence", 0)*100)}%)</h3><p>Status: <code>{h.get("status")}</code></p><strong>Supporting Evidence:</strong><ul>{"".join(f"<li>{e}</li>" for e in h.get("supporting_evidence", []))}</ul></div>' for h in data.get("top_hypotheses", []))}
  
  <h2>Action Items</h2>
  <div class="card"><ul>{"".join(f"<li>{a}</li>" for a in data.get("action_items", []))}</ul></div>
</body>
</html>"""
